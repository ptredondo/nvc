library(nvc)
set.seed(2026)
x <- matrix(rnorm(4000), ncol = 2)
y <- matrix(rnorm(4000), ncol = 2)
stopifnot(is.finite(xi(x, y[, 1])))
stopifnot(is.finite(xi.vec(x, y)))
stopifnot(isTRUE(all.equal(xi.vec(x, y), xi.vec(x, y[, 2:1]), tolerance = 1e-10)))
stopifnot(identical(names(xi(x, y[, 1], nboot = 3)), c("xi", "pval")))
v <- xi.vec(x, y, nboot = 3, ncores = 1)
stopifnot(identical(names(v), c("xi.vec", "pval")), v$pval >= 0, v$pval <= 1)
fit <- nvc(x, y, blength = 100)
stopifnot(identical(names(fit), c("freq", "nvc")), length(fit$nvc) == 50L)
fit <- nvc(x, y, blength = 100, nboot = 3, ncores = 1)
stopifnot(identical(names(fit), c("freq", "nvc", "pval", "pval.adj")))
stopifnot(all(fit$pval >= 0 & fit$pval <= 1))
freq.ind <- c(3L, 12L, 25L)
freq.sub <- fit$freq[freq.ind]
fit.full <- nvc(x, y, blength = 100)
fit.sub <- nvc(x, y, blength = 100, freq = freq.sub)
stopifnot(identical(fit.sub$freq, freq.sub),
          isTRUE(all.equal(fit.sub$nvc, fit.full$nvc[freq.ind])))
fit.sub.test <- nvc(x, y, blength = 100, freq = freq.sub, nboot = 3, ncores = 1)
stopifnot(identical(fit.sub.test$freq, freq.sub),
          isTRUE(all.equal(fit.sub.test$nvc, fit.sub$nvc)),
          length(fit.sub.test$pval) == length(freq.sub),
          all(fit.sub.test$pval >= 0 & fit.sub.test$pval <= 1),
          isTRUE(all.equal(fit.sub.test$pval.adj, p.adjust(fit.sub.test$pval, method = "BH"))))
cfit <- coh(x[, 1], x[, 1], blength = 100)
stopifnot(all(abs(cfit$coh - 1) < 1e-10))
cc <- cancoh(x, y, blength = 100)
stopifnot(identical(names(cc), c("freq", "cancoh")), length(cc$freq) == 51L)
stopifnot(all(cc$cancoh >= 0 & cc$cancoh <= 1, na.rm = TRUE))
stopifnot(length(extract.fband(x[, 1], 100)) == 5L)
stopifnot(identical(dim(sim.fband(10, 100, c("alpha", "beta2"))), c(1000L, 2L)))
stopifnot(length(band.coh(x[, 1], y[, 1], l_max = 2, fband = "alpha")) == 1L)
stopifnot(length(kencoh(x, y, fband = "alpha")) == 1L)
stopifnot(!any(c("kencoh.core", "kencoh.eigen") %in% getNamespaceExports("nvc")))
